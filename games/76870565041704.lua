run(function()
	minecraft = setmetatable({
		Controller = require(lplr.PlayerScripts.MC.Controller),
		Config = require(replicatedStorage.MC.Config),
		Net = require(lplr.PlayerScripts.MC.Net),
		Physics = require(replicatedStorage.MC.Physics)
	}, {})

	local remoteNames = {
		Action = replicatedStorage.MC.Remotes.Action
	}

	for i, v in remoteNames do
		remotes[i] = v
	end

	store.BlockSize = minecraft.Config.BLOCK or 3

	minecraft.getEntityId = function(model)
		return model:GetAttribute("EntityId") or 0
	end

	minecraft.look = function(vector)
        local eye = minecraft.Controller.eye()

        local block = vector / store.BlockSize
        local direction = block - eye

        if direction.Magnitude >= 1e-6 then
            minecraft.Controller.yaw = math.atan2(-direction.X, -direction.Z)

            local horizontal = math.sqrt(direction.X * direction.X + direction.Z * direction.Z)
            minecraft.Controller.pitch = math.clamp(-math.atan2(direction.Y, horizontal), -math.pi / 2, math.pi / 2)
        end
    end

	minecraft.attack = function(entity, Net)
		if minecraft.Controller and minecraft.Controller.state then
			local entityId = minecraft.getEntityId(entity)
			local look = gameCamera.CFrame.LookVector

			if Net then
				minecraft.Net.send({
    	            a = "attack",
        	        st = {
            	        pos = minecraft.Controller.state.pos,
                    	vel = minecraft.Controller.state.vel,
                	    sprint = minecraft.Controller.state.sprinting,
            	        fall = minecraft.Controller.state.fallDistance,
        	            gliding = minecraft.Controller.state.gliding,
    	                water = minecraft.Controller.state.inWater,
	                    ground = minecraft.Controller.state.onGround,
                    	swap = false,
                	    predicted = true,
            	        look = look,
        	        },
    	            target = entityId
	            })
			else
				remotes.Action:FireServer({
					a = "attack",
        	        st = {
            	        pos = minecraft.Controller.state.pos,
                    	vel = minecraft.Controller.state.vel,
                	    sprint = minecraft.Controller.state.sprinting,
            	        fall = minecraft.Controller.state.fallDistance,
        	            gliding = minecraft.Controller.state.gliding,
    	                water = minecraft.Controller.state.inWater,
	                    ground = minecraft.Controller.state.onGround,
                    	swap = false,
                	    predicted = true,
            	        look = look,
        	        },
    	            target = entityId
				})
			end
		end
	end
end)

